"""Local recovery snapshots and startup acknowledgement. Never sends data off-device."""
import hashlib
import json
import os
import re
from pathlib import Path
import tempfile
import threading
from datetime import datetime, timezone

MAX_BACKUP = 12_000_000
KEEP = 5
DATA_KEYS = {'favorites', 'inventory', 'profiles', 'collection', 'materials', 'lang', 'theme'}


def atomic_json(path, data):
    # Store adjacent temporary file so replacement is atomic on the same volume.
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(dir=path.parent, prefix='.tmp-')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            json.dump(data, stream, ensure_ascii=False, allow_nan=False, separators=(',', ':'))
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def read_json(path, default=None):
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return default


def validate_snapshot(raw):
    # The UI performs full record validation; the native boundary enforces envelope, keys and size.
    if not isinstance(raw, str) or len(raw.encode('utf-8')) > MAX_BACKUP:
        raise ValueError('Invalid backup size')
    value = json.loads(raw)
    if not isinstance(value, dict) or value.get('format') != 'mhf-skill-backup' or type(value.get('version')) is not int or value['version'] != 1:
        raise ValueError('Invalid backup format')
    data = value.get('data')
    if not isinstance(data, dict) or set(data) != DATA_KEYS:
        raise ValueError('Invalid backup fields')
    if not all(isinstance(data[k], list) for k in ('favorites', 'profiles')) or not all(isinstance(data[k], dict) for k in ('inventory', 'collection', 'materials')) or data['lang'] not in ('ja', 'en') or data['theme'] not in ('light', 'dark'):
        raise ValueError('Invalid backup data')
    return value


def record_history(root, status, version):
    # Limit the local update journal; never record personal data or credentials.
    path = root / 'update_history.json'
    rows = read_json(path, [])
    if not isinstance(rows, list):
        rows = []
    rows = [{'at': datetime.now(timezone.utc).isoformat(), 'status': status, 'version': version}, *rows][:30]
    atomic_json(path, rows)


def snapshots(folder):
    # Do not include the separately retained pre-update checkpoint in rotation.
    return sorted((p for p in folder.glob('*.json') if re.fullmatch(r'[0-9a-f]{64}\.json', p.name) and p.is_file() and not p.is_symlink()),
                  key=lambda p: p.stat().st_mtime_ns, reverse=True)


def save_snapshot(folder, raw):
    value = validate_snapshot(raw)
    # Deduplicate on content, not the timestamp generated by the UI.
    canonical = json.dumps(value['data'], ensure_ascii=False, sort_keys=True, allow_nan=False)
    key = hashlib.sha256(canonical.encode()).hexdigest()
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / (key + '.json')
    if target.exists():
        os.utime(target, None)
    else:
        atomic_json(target, value)
    # The pre-update checkpoint is separate and not pruned by ordinary saves.
    files = snapshots(folder)
    for old in files[KEEP:]:
        old.unlink()
    return target


def checkpoint(folder):
    # Use the last successful logical backup; never open or copy a live WebView2 database.
    files = snapshots(folder)
    for file in files:
        try:
            value = validate_snapshot(file.read_text(encoding='utf-8'))
        except (OSError, ValueError):
            continue
        atomic_json(folder / 'before-update.json', value)
        return True
    if files:
        raise ValueError('No valid saved-data checkpoint')
    return False


class DesktopBridge:
    def __init__(self, folder, url, startup_report=None, root=None):
        self._folder = folder
        self._url = url
        self._report = startup_report
        self._root = root
        self._window = None
        self._lock = threading.Lock()

    def _verify_origin(self):
        if self._window is None or self._window.get_current_url() != self._url:
            raise ValueError('Desktop bridge is only available on the local simulator page')

    def save_backup(self, raw):
        self._verify_origin()
        with self._lock:
            save_snapshot(self._folder, raw)
        return True

    def startup_ready(self):
        self._verify_origin()
        with self._lock:
            if self._report is not None:
                atomic_json(self._report, {'ready': True})
                self._report = None
        return True

    def version_information(self):
        self._verify_origin()
        if self._root is None:
            raise ValueError('Desktop settings unavailable')
        from desktop_info import information
        return information(self._root, self._folder.parent)

    def configure_updates(self, startup, channel):
        self._verify_origin()
        if self._root is None:
            raise ValueError('Desktop settings unavailable')
        from desktop_info import configure
        with self._lock:
            return configure(self._root, startup, channel)

    def discover_updates(self):
        self._verify_origin()
        if self._root is None:
            raise ValueError('Desktop settings unavailable')
        from desktop_info import discover
        return discover(self._root)
