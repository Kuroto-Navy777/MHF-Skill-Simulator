# Partial summaries of matched source rows are distinct from complete translations.
def skill_summary(row, original):
    if not original:
        return None
    if row['ja'] in SKILL:
        return SKILL[row['ja']]
    for pattern, text in PATTERNS:
        m=re.fullmatch(pattern,original)
        if m: return text.format(*m.groups())
    name=row['ja']
    if re.fullmatch(r'.+技【(未熟|達人|皆伝)】', name):
        effects=[]
        if '0.8x' in original: effects.append('攻撃力が0.8倍になる')
        if 'Fencing' in original: effects.append('剣術効果')
        if 'Evade Distance Up' in original: effects.append('回避距離UP')
        if '1.1x' in original: effects.append('攻撃力が1.1倍になる')
        if 'bouncing off' in original: effects.append('弾かれる弾の確率を低減する')
        if 'no longer deflected' in original: effects.append('矢が弾かれなくなる')
        if effects: return '対応武器を使用中：'+'、'.join(effects)+'。'
    return None

